static char map_single_char(uint8_t code) {
    if (code >= 0x80 && code <= 0x89) return '0' + (code - 0x80);
    if (code >= 0x8A && code <= 0xA3) return 'A' + (code - 0x8A);
    if (code >= 0xA4 && code <= 0xBD) return 'a' + (code - 0xA4);
    switch (code) {
        case 0xBE: return '\'';
        case 0xBF: return ',';
        case 0xC0: return '.';
        case 0xC1: return ' ';
        case 0xC2: return '-';
        case 0xC4: return '!';
        case 0xC5: return '?';
        case 0xFF: return ' ';
        default: return ' ';
    }
}

std::string TextDecoder::decode_char(uint8_t code) {
    if (code >= 0x1A && code <= 0x69) {
        uint8_t idx = code - 0x1A;
        std::string res;
        char c1 = map_single_char(lut_DTE1[idx]);
        char c2 = map_single_char(lut_DTE2[idx]);
        res += c1;
        res += c2;
        return res;
    }
    return std::string(1, map_single_char(code));
}

std::string TextDecoder::decode_string(const uint8_t* data, size_t length) {
    std::string result;
    for (size_t i = 0; i < length; ++i) {
        uint8_t code = data[i];
        if (code == 0x00) break;
        if (code == 0x05) {
            result += '\n';
        } else if (code >= 0x1A && code <= 0x69) {
            result += decode_char(code);
        } else if (code >= 0x80) {
            result += map_single_char(code);
        }
    }
    return result;
}

std::string TextDecoder::decode_null_terminated(const uint8_t* data, size_t max_length) {
    std::string result;
    for (size_t i = 0; i < max_length; ++i) {
        uint8_t code = data[i];
        if (code == 0x00) break;
        if (code == 0x05) {
            result += '\n';
        } else if (code >= 0x1A && code <= 0x69) {
            result += decode_char(code);
        } else if (code >= 0x80) {
            result += map_single_char(code);
        }
    }
    return result;
}

