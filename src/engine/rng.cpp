RNG::RNG() : table_(default_nes_rng) {}

void RNG::load_table(const uint8_t* table_256_bytes) {
    if (table_256_bytes) {
        std::copy_n(table_256_bytes, 256, table_.begin());
    }
}

uint8_t RNG::next_byte() {
    index_ = (index_ + 1) & 0xFF;
    return table_[index_];
}

int RNG::next_range(int min_val, int max_val) {
    if (min_val >= max_val) return min_val;
    uint8_t r = next_byte();
    int span = (max_val - min_val) + 1;
    return min_val + (r % span);
}

