void Font::draw_string(uint32_t* pixel_buffer, int pitch, int tile_x, int tile_y, const std::string& text, uint32_t color) {
    if (!pixel_buffer) return;

    int cur_x = tile_x * 8;
    int cur_y = tile_y * 8;

    for (char c : text) {
        if (c == '\n') {
            cur_x = tile_x * 8;
            cur_y += 8;
            continue;
        }

        uint8_t u = static_cast<uint8_t>(c);
        if (u >= 'a' && u <= 'z') u = u - 'a' + 'A';
        if (u >= 128) u = ' ';

        const uint8_t* glyph = font_8x8[u];
        for (int r = 0; r < 8; ++r) {
            uint8_t row = glyph[r];
            for (int b = 0; b < 8; ++b) {
                if (row & (0x80 >> b)) {
                    int px = cur_x + b;
                    int py = cur_y + r;
                    if (px >= 0 && px < 256 && py >= 0 && py < 240) {
                        pixel_buffer[py * pitch + px] = color;
                    }
                }
            }
        }
        cur_x += 8;
    }
}

